"""
make_gapconf_devices.py  (Mac)  -- best_devices/
Best devices whose breathing mode sits INSIDE the mirror cell's Y+Z+ (breathing-class) gap (user requirement 2026-10-19).
Source: runs/surrogate_explore/gapconf/<tag>/data/{final,figsolve,fields,bands}.npz (gapconf.py, gapconf_figs.py).
Writes best_devices/<device>/{mirror_bands.png, review.png, summary.md, summary.json} and best_devices/README.md.
Run from the project root:  python best_devices/make_gapconf_devices.py
Older devices (breathing mode above the gap): best_devices/not_gap_confined/.
"""
import json
import shutil
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, 'runs/surrogate_explore')
import plot_gapconf as PG   # noqa: E402

OUT = Path('best_devices'); G = Path('runs/surrogate_explore/gapconf'); SHD = Path('runs/shield_619/figures')
HBAR, C = 1.054571817e-34, 299792458.0
BEST = {'60 nm': 'w650_m186_c455_d086'}          # one per minimum feature; 80 nm: none yet (needs a width taper)


def info(tag):
    dd = G / tag / 'data'
    z = np.load(dd / 'fields.npz'); B = np.load(dd / 'bands.npz'); zs = np.load(dd / 'figsolve.npz')
    c = json.loads(str(z['cfg'])); S = PG.solve_summary(zs)
    F = PG.clean_bands(B['mirror_f_mech'][:, 0]); lo, hi = PG.yz_gap(F, B['mirror_k_frac'])
    meff = float(z['meff']); fb = float(z['f_breath'])
    xzpf = np.sqrt(HBAR / (2 * meff * 2 * np.pi * fb)); sc = xzpf / (float(z['umax']) * 1e-9)
    sv = z['strain_mid_val']
    mf = {k: float(zs[k]) for k in ('bridge', 'rail', 'hole')}
    return dict(tag=tag, cfg=c, lam=C / float(z['f_opt']) * 1e9, Q=float(z['Q_opt']), fb=S['fb'], others=[float(x) for x in S['others']],
                loc=float(z['loc_breath']), S=float(z['S_breath']), gap=(lo, hi), margin=hi - S['fb'],
                meff_fg=meff * 1e18, xzpf_fm=xzpf * 1e15, eps_vol=float(np.abs(sv[:, :3].sum(1)).max() * sc),
                eps_dif=float(np.abs(sv[:, 0] - sv[:, 1]).max() * sc), min_feature=mf,
                clamp=float(zs['clamp_frac'][int(z['i_breath']) - 1]))


def slug(mf, r):
    c = r['cfg']
    return f"{mf.replace(' ', '')}_w{c['w']:g}_d{c['d']}_xi{c['xi']:g}_chi{c['chi']:g}_gapconf"


rows = {t: info(t) for t in PG.TAGS if (G / t / 'data' / 'bands.npz').exists()}
lines = ['# Best 1D nanobeam OMC devices (diamond, 619 nm, t 120 nm)', '',
         '**Requirement (user, 2026-10-19): the breathing mode must sit INSIDE the mirror cell\'s breathing-class (Y+Z+) gap.**',
         'Devices that fail it are in `not_gap_confined/` (superseded 2026-10-20).', '',
         'Generated by `python best_devices/make_gapconf_devices.py`. COMSOL, ideal geometry, vertical walls, M 10, 10 mirror cells.', '',
         '| min feature | device | w | a | taper (d, ξ, χ) | λ (nm) | optical Q | breathing (GHz) | mirror Y+Z+ gap (GHz) | margin | min feat. |',
         '|---|---|---|---|---|---|---|---|---|---|---|']
for mf, tag in BEST.items():
    r = rows[tag]; c = r['cfg']; s = slug(mf, r); od = OUT / s; od.mkdir(exist_ok=True)
    dd = G / tag / 'data'
    fig, ax = plt.subplots(1, 2, figsize=(13, 5))
    PG.plot_bands(ax[0], ax[1], np.load(dd / 'bands.npz'), PG.solve_summary(np.load(dd / 'figsolve.npz')), r['lam'])
    fig.suptitle(f"mirror cell: w {c['w']:g}, a {c['a_m']:.1f}, hx {c['hx_m']:.1f}, hy {c['hy_m']:.1f}, t {c['t']} nm "
                 f"(dashed: center cell)", fontsize=10)
    fig.tight_layout(); fig.savefig(od / 'mirror_bands.png', dpi=150); plt.close(fig)
    shutil.copy(G / 'figures' / f'{tag}.png', od / 'review.png')
    for f in (('cell_compare', 'shield_cell_bands'), ('structure', 'shield_structure'), ('disp_maps', 'shield_disp_maps'), ('qm_table', 'shield_qm')):
        if tag == 'w650_m186_c455_d086' and (SHD / f'{f[0]}.png').exists():
            shutil.copy(SHD / f'{f[0]}.png', od / f'{f[1]}.png')
    json.dump(dict(r, gap=list(r['gap'])), open(od / 'summary.json', 'w'), indent=1)
    lo, hi = r['gap']; m = r['min_feature']
    (od / 'summary.md').write_text('\n'.join([
        f'# {s}', '', f'Gap-confined {mf} device (design tag `{tag}`, `runs/surrogate_explore/gapconf/{tag}`).', '',
        '| | |', '|---|---|',
        f"| beam width / thickness | {c['w']:g} nm / {c['t']} nm |",
        f"| mirror cell | a {c['a_m']:.1f} nm, hx {c['hx_m']:.1f} (hx/a {c['hx_m']/c['a_m']:.2f}), hy {c['hy_m']:.1f} (hy/w {c['hy_m']/c['w']:.2f}) |",
        f"| taper | M {c['M']}, d {c['d']}, η {c['eta']}, ξ {c['xi']:g}, χ {c['chi']:g} (center holes larger than the mirror's); {c['n_mirror']} mirror cells |",
        f"| resonance / optical Q | {r['lam']:.2f} nm / {r['Q']:.2g} |",
        f"| breathing mode | {r['fb']:.2f} GHz, localization {r['loc']:.2f}, sidewall ratio S {r['S']:.2f} |",
        f"| mirror Y+Z+ gap | {lo:.2f}–{hi:.2f} GHz (13 k-points); breathing mode {r['margin']:.2f} GHz below the top |",
        f"| displacement fraction in the last 500 nm | {r['clamp']:.1e} (decays inside the mirror) |",
        f"| other localized breathing-like modes | {', '.join(f'{x:.2f}' for x in r['others'])} GHz |",
        f"| m_eff / x_zpf | {r['meff_fg']:.0f} fg / {r['xzpf_fm']:.2f} fm |",
        f"| zero-point strain (midplane peak) | volumetric {r['eps_vol']:.1e}, εxx−εyy {r['eps_dif']:.1e} |",
        f"| smallest features | bridge {m['bridge']:.0f}, rail {m['rail']:.0f}, hole {m['hole']:.0f} nm |", '',
        '## Figures', '- `mirror_bands.png`: mirror-cell bands (solid) and center-cell bands (dashed), optics and mechanics, with the cavity modes drawn where they sit.',
        '- `review.png`: bands + optical Ey + breathing mode on the deformed top face + midplane strain maps (volumetric, εxx−εyy) with the optical |E|² = 50 % contour.',
        f'- `{s}.gds` / `.png`: layout, plain anchors; `{s}_shield.gds` / `.png`: with the cross shield (layers 1 diamond, 2 etch, 10 label; `python best_devices/make_gds.py`).',
        '- `shield_cell_bands.png`, `shield_structure.png`, `shield_disp_maps.png`, `shield_qm.png`: shield cell bands (COMSOL vs Dmitry cloud), modeled structure, breathing-mode |u|² with/without shield, Q_m vs mirror cells. Full report: `docs/shield_report/omc_shield_report.pdf`.',
        '- **Fab note:** the first shield column leaves a 30 nm strip at the trench edge (cross center a/2 = 225 nm, bar half-length 195 nm), below the 60 nm rule; same in the COMSOL model. Fix (needs a re-run): shift the lattice ≥ 30 nm away from the trench or shorten the edge crosses.', '',
        '## Phonon shield (2026-10-22)', '- Cross shield (a 450, h 390, w 140 nm; gap 9.40–11.47 GHz) around the anchor: Q_m 1.65e7 → 2.8e9 (10 mirror cells, COMSOL anchor loss; PML/mesh converged). `runs/shield_619`, `docs/shield_report/omc_shield_report.pdf`.', '',
        '## Not yet done', '- Disorder (σ 1–2 nm), Lumerical check, g0 (bug), longer mirror, sidewall angles. See `../CHECKS.md`.', '']))
    lines.append(f"| {mf} | [{s}]({s}/summary.md) | {c['w']:g} | {c['a_m']:.1f} | {c['d']}, {c['xi']:g}, {c['chi']:g} | {r['lam']:.2f} | {r['Q']:.2g} | "
                 f"{r['fb']:.2f} | {lo:.2f}–{hi:.2f} | {r['margin']:.2f} | {min(m.values()):.0f} |")
    print('wrote', od)
lines += ['| 80 nm | none yet: no 80 nm mirror/center pair puts the breathing mode in the gap (needs a width taper) | | | | | | | | | |', '',
          '## All gap-confined designs (60 nm)', '',
          '| design | w | a | taper (d, ξ, χ) | λ (nm) | optical Q | breathing (GHz) | gap (GHz) | margin | review figure | GDS |', '|---|---|---|---|---|---|---|---|---|---|---|']
for t, r in sorted(rows.items(), key=lambda kv: -kv[1]['Q']):
    c = r['cfg']; lo, hi = r['gap']
    lines.append(f"| {t} | {c['w']:g} | {c['a_m']:.1f} | {c['d']}, {c['xi']:g}, {c['chi']:g} | {r['lam']:.2f} | {r['Q']:.2g} | {r['fb']:.2f} | "
                 f"{lo:.2f}–{hi:.2f} | {r['margin']:.2f} | [png](../runs/surrogate_explore/gapconf/figures/{t}.png) | [gds](gds/{t}.gds) |")
lines += ['', '**Cross phonon shield (best device, 2026-10-22):** Q_m (anchor loss, COMSOL, 10 mirror cells) 1.65e7 plain anchor → 2.8e9 with 4 shield periods '
          '(160–260× at 2/4/10 mirror cells; PML/mesh converged). Shield cell a 450, h 390, w 140 nm, gap 9.40–11.47 GHz (designed on the Dmitry cloud, '
          'COMSOL-checked). Report: `docs/shield_report/omc_shield_report.pdf`.', '',
          'GDS layouts: `python best_devices/make_gds.py` (every design above in `gds/`, the best device with and without the shield in its folder, the older devices in `not_gap_confined/<device>/`).']
lines += ['', 'The first gap-confined set is also the frozen spec for the authorized Dmitry-service run: `runs/dmitry/gapconf1_dmitry/designs_dmitry.json` (not submitted).', '']
(OUT / 'README.md').write_text('\n'.join(lines))
print('wrote best_devices/README.md')

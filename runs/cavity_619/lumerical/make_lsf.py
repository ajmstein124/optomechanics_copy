"""
make_lsf.py  (Mac)
Generate self-contained Lumerical FDTD scripts (.lsf) that replicate a COMSOL cavity sweep's optics
(resonance + Q, and the Ey field map) point by point. Hole layouts come from scripts/cavity_taper.py
(same as COMSOL), written into the script as matrices -> identical geometry.

Q method = the lab's: Lumerical 'Qanalysis' analysis group (getresult("Qanalysis","Q")), as in
C:\\Users\\hopel\\Documents\\Abby\\SiC_AL2O3_Di_Nanobeams_radpitch_Q_sweep.lsf and the Lumerical
'1D high-Q cavity' example.

Each generated script has switches at the top:
  do_run = 0        build ONE point (check_point) and save <name>_check.fsp for GUI inspection
  basedir = ""      output folder ("" = the current working directory, printed at start); all files are
                    prefixed with the sweep name, no subfolder (portable to any PC)
  do_run = 1        run points first_point..last_point: per point build -> save -> run ->
                    Qanalysis (lambda, Q of all resonances found) + z=0 Ey profile at the
                    highest-Q resonance -> <name>_pt<i>.mat, one line per point in <name>_summary.txt
  keep_fsp = 0/1    keep every point's solved .fsp (large) or overwrite one working file
  use_symmetry = 1  (default since 2026-10-15) x/y anti-symmetric, z symmetric = COMSOL's mode class, ~8x faster;
                    0 = full beam (independent of COMSOL's symmetry choices); 1 = x/y anti-symmetric,
                    z symmetric (8x faster, same classes as COMSOL)
Usage (from project root):
    python runs/cavity_619/lumerical/make_lsf.py
"""

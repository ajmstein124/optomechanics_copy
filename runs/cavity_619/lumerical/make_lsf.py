def points_ad(cell, a_list, d_list, xi, chi):
    return [dict(a=a, d=d, xi=xi, chi=chi) for d in d_list for a in a_list]


def comsol_opt(z):
    """COMSOL cavity resonance, as cavity_pipeline.Pipeline.load (no mph import on the Mac)."""
    io = int(z['i_opt'])
    if 'Q' not in z:                                   # older sweep files: most localized mode with Q > 1e3
        ok = z['Q_opt'] > 1e3
        io = int(np.where(ok)[0][np.argmax(z['loc_opt'][ok])]) + 1 if ok.any() else io
    return dict(lam=299792.458 / (z['f_opt'][io - 1] / 1e12), Q=float(z['Q_opt'][io - 1]))


def points_from_dir(data_dir, prefix):
    """Points of a finished COMSOL sweep: one per solved <prefix>*.npz (skipped/infeasible dropped), with the
    COMSOL resonance and Q attached for comparison (comsol_lam_nm, comsol_Q). Returns (cell, points)."""
    pts, cell = [], None
    for fn in sorted(Path(data_dir).glob(f'{prefix}*.npz')):
        z = np.load(fn)
        if 'skipped' in z and bool(z['skipped']):
            continue
        c = json.loads(str(z['cfg']))
        cc = dict(w=c['w'], t=c['t'], hx_a=round(c['hx_m'] / c['a_m'], 4), hy_w=round(c['hy_m'] / c['w'], 4))
        assert cell is None or (cc['w'], cc['hy_w']) == (cell['w'], cell['hy_w']), fn
        cell = cell or cc
        r = comsol_opt(z)
        pts.append(dict(a=c['a_m'], d=c['d'], xi=c['xi'], chi=c['chi'], comsol_lam_nm=round(r['lam'], 2),
                        comsol_Q=float(f"{r['Q']:.3g}"), file=fn.name))
    pts.sort(key=lambda q: (q['d'], q['xi'], q['chi'], q['a']))
    return cell, pts


def mat(rows, fmt='{:.4f}'):
    return '[' + ';\n  '.join(', '.join(fmt.format(v) for v in r) for r in rows) + ']'


def write_lsf(name, cell, pts, check_point, note):
    w, t, n = cell['w'], cell['t'], cell.get('n', 2.41)
    L = [layout(p['a'], cell['hx_a'] * p['a'], cell['hy_w'] * w, 10, 10, p['d'], 1.0, p['xi'], p['chi']) for p in pts]
    nh = len(L[0]['x'])
    X = [l['x'] for l in L]; HX = [l['hx'] for l in L]; HY = [l['hy'] for l in L]
    XE = [beam_half_length(l, 1000.0) for l in L]
    P = [[p['a'], p['d'], p['xi'], p['chi']] for p in pts]
    s = f"""# {name}.lsf  -- generated by runs/cavity_619/lumerical/make_lsf.py (do not edit by hand)
# {note}
# Cell: w {w} nm, t {t} nm, hx/a {cell['hx_a']}, hy/w {cell['hy_w']}, n {n}; taper M 10, eta 1, 10 mirror cells,
# {nh} holes per half beam (hole 1 = center). Lengths below in nm.
# Q method: Qanalysis analysis group (lab standard). Field map: 2D z-normal profile at z = 0,
# start-apodized (source transient removed), saved at the highest-Q resonance.

do_run       = 0;          # 0 = build check_point and save <name>_check.fsp ; 1 = run the sweep
check_point  = {check_point};
first_point  = 1;
last_point   = {len(pts)};
keep_fsp     = 0;
use_symmetry = 1;          # 1 = x/y anti-symmetric, z symmetric (COMSOL mode class, ~8x faster); 0 = full beam
sim_time     = 1.5e-12;    # resonance converges well within this; Q ~1e7 cannot be resolved by any practical time
basedir      = "";         # output folder; "" = current working directory (printed below; set a full path if needed)
name         = "{name}";

w = {w}e-9; t = {t}e-9; n_d = {n}; nm = 1e-9;
lam_lo = 570e-9; lam_hi = 680e-9;
pad = 900e-9;
npts = {len(pts)}; nh = {nh};
# per point: a, d, xi, chi
PAR = {mat(P, '{:.6g}')};
# hole centers / full axes per point (nm), holes j = 1..nh (1 = center)
HXC = {mat(X)};
HXA = {mat(HX)};
HYA = {mat(HY)};
XEND = {mat([[v] for v in XE])};   # beam half length inside the PML (nm)

if (do_run == 1) {{ ip0 = first_point; ip1 = last_point; }} else {{ ip0 = check_point; ip1 = check_point; }}
# all outputs go straight into basedir, prefixed with the sweep name (no subfolder: Lumerical cannot create folders)
if (length(basedir) == 0) {{ basedir = pwd; }}
outdir = basedir;
?"Output folder: " + outdir;
sumfile = outdir + "/" + name + "_summary.txt";
# rm() is disabled in safe mode: delete an old summary by hand (or via the runner) before a fresh sweep
if (do_run == 1 & fileexists(sumfile) == 0) {{
    write(sumfile, "point a_nm d xi chi lambda_nm Q n_res");
}}

for (ip = ip0:ip1) {{
    switchtolayout;
    deleteall;
    xend = XEND(ip) * nm;
    a = PAR(ip, 1) * nm;

    # --- source, monitors, analysis (creation order: source -> monitors -> FDTD -> structures)
    adddipole; set("name", "dipole");
    set("x", 0.5 * (HXA(ip, 1) / 2 + HXC(ip, 2) - HXA(ip, 2) / 2) * nm); set("y", 0); set("z", 0);
    set("theta", 90); set("phi", 90);
    set("wavelength start", lam_lo); set("wavelength stop", lam_hi);

    addobject("Qanalysis"); set("name", "Qanalysis");
    set("x", 0); set("y", 0); set("z", 0);
    set("x span", 2 * HXC(ip, 3) * nm); set("y span", 0.3 * w); set("z span", 0);
    set("nx", 4); set("ny", 2); set("nz", 1);
    set("t start", 250e-15); set("f min", c / lam_hi); set("f max", c / lam_lo);
    if (use_symmetry == 1) {{ set("x", HXC(ip, 3) * nm); set("y", 0.15 * w); }}   # probes inside the simulated octant

    addprofile; set("name", "profile_z0"); set("monitor type", "2D Z-normal");
    set("x", 0); set("x span", 2 * min([HXC(ip, nh), 3000]) * nm); set("y", 0); set("y span", w + 1000e-9); set("z", 0);
    set("override global monitor settings", 1); set("use source limits", 1); set("frequency points", 201);
    set("apodization", "Start"); set("apodization center", 300e-15); set("apodization time width", 60e-15);

    addfdtd;
    set("x", 0); set("x span", 2 * xend); set("y", 0); set("y span", w + 2 * pad); set("z", 0); set("z span", t + 2 * pad);
    set("mesh type", "auto non-uniform"); set("mesh accuracy", 3);
    set("dt stability factor", 0.95); set("simulation time", sim_time);
    set("x min bc", "PML"); set("x max bc", "PML"); set("y min bc", "PML"); set("y max bc", "PML");
    set("z min bc", "PML"); set("z max bc", "PML");
    if (use_symmetry == 1) {{ set("x min bc", "Anti-Symmetric"); set("y min bc", "Anti-Symmetric"); set("z min bc", "Symmetric"); }}

    addmesh; set("name", "mesh_beam");
    set("x", 0); set("x span", 2 * (HXC(ip, nh) + 2 * PAR(ip, 1)) * nm); set("y", 0); set("y span", w + 60e-9);
    set("z", 0); set("z span", t + 40e-9); set("dx", 10e-9); set("dy", 10e-9); set("dz", 10e-9);

    # --- structures: beam through the x PML, then the holes (mesh order 1 beats the beam's 2)
    addrect; set("name", "beam");
    set("x", 0); set("x span", 2 * xend + 4e-6); set("y", 0); set("y span", w); set("z", 0); set("z span", t);
    set("material", "<Object defined dielectric>"); set("index", n_d);
    set("override mesh order from material database", 1); set("mesh order", 2);
    for (j = 1:nh) {{
        for (s = -1:2:1) {{
            if (j > 1 | s == 1) {{
                addcircle; set("name", "hole_" + num2str(j));
                set("make ellipsoid", 1);
                set("radius", HXA(ip, j) / 2 * nm); set("radius 2", HYA(ip, j) / 2 * nm);
                set("x", s * HXC(ip, j) * nm); set("y", 0); set("z", 0); set("z span", t + 40e-9);
                set("material", "<Object defined dielectric>"); set("index", 1);
                set("override mesh order from material database", 1); set("mesh order", 1);
            }}
        }}
    }}

    if (do_run == 0) {{
        save(outdir + "/" + name + "_check.fsp");
        ?"Saved check file for point " + num2str(ip) + ": a = " + num2str(PAR(ip, 1)) + " nm, d = " + num2str(PAR(ip, 2));
    }} else {{
        if (keep_fsp == 1) {{ fsp = outdir + "/" + name + "_pt" + num2str(ip) + ".fsp"; }}
        else {{ fsp = outdir + "/" + name + "_work.fsp"; }}
        save(fsp);
        run;
        if (haveresult("Qanalysis", "Q")) {{
            Qr = getresult("Qanalysis", "Q"); lamr = Qr.lambda; Qv = Qr.Q; nres = length(Qv);
        }} else {{ lamr = 0; Qv = 0; nres = 0; }}   # no resonance in [lam_lo, lam_hi] (e.g. a 225, d .10 -> ~684 nm)
        if (nres > 0) {{
            ib = find(Qv == max(Qv)); ib = ib(1);
            lam_best = lamr(ib); Q_best = Qv(ib);
        }} else {{ lam_best = 0; Q_best = 0; }}
        xg = getdata("profile_z0", "x"); yg = getdata("profile_z0", "y"); fg = getdata("profile_z0", "f");
        Ey = getdata("profile_z0", "Ey");
        if (nres > 0) {{ df = abs(fg - c / lam_best); k = find(df == min(df)); k = k(1); }} else {{ k = 1; }}
        Ey_res = pinch(Ey, 4, k); f_map = fg(k);
        a_nm = PAR(ip, 1); d_par = PAR(ip, 2); xi_par = PAR(ip, 3); chi_par = PAR(ip, 4);
        matlabsave(outdir + "/" + name + "_pt" + num2str(ip) + ".mat", a_nm, d_par, xi_par, chi_par,
                   lamr, Qv, lam_best, Q_best, xg, yg, Ey_res, f_map);
        write(sumfile, num2str(ip) + " " + num2str(a_nm) + " " + num2str(d_par) + " " + num2str(xi_par) + " " +
              num2str(chi_par) + " " + num2str(lam_best * 1e9) + " " + num2str(Q_best) + " " + num2str(nres));
        ?"point " + num2str(ip) + "/" + num2str(npts) + ": lambda = " + num2str(lam_best * 1e9) + " nm, Q = " + num2str(Q_best);
    }}
}}
"""
    fn = OUT / f'{name}.lsf'
    fn.write_text(s)
    json.dump(dict(cell=cell, points=pts, note=note), open(OUT / f'{name}_points.json', 'w'), indent=1)
    print(f'wrote {fn} ({len(pts)} points, check point {check_point}: {pts[check_point-1]})')
    return fn



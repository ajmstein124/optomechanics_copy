"""
sweep_plan.py  (runs locally on Mac; needs shapely)
Build a sweep plan for unit_cell_3.mph snowflake runs, with an optional
minimum-feature-size (fabrication) check.

For every (a, d/a, w/a) combo it computes, from the geometry read out of the .mph
(see scripts/cell_placement.py):
  - fillet-aware cell shift (mov1, applied to wp1 slab + wp2 air) and hole clearance
  - narrowest slab bridge between the hole and its periodic images   (solid feature)
  - arm width w                                                       (hole feature)
and assigns a status:
  ok                 -> runs
  infeasible_geom    -> hole cannot fit the rhombus cell (never runs)
  below_min_feature  -> bridge or w < min feature; runs only if the check is OFF
                        (still flagged in the plan so analysis can grey it out)

The minimum feature check is ON by default with DEFAULT_MIN_FEATURE_NM. Turn it off
for exploratory sweeps with --no-min-feature (combos are then run but still flagged),
or change the threshold with --min-feature <nm>.

Usage (from project root):
    python scripts/sweep_plan.py --name diamond_a_large \\
        --a 400:1000:100 --da 0.41,0.45,0.48 --wa 0.22,0.26,0.30 \\
        [--min-feature 50 | --no-min-feature] [--n-mode 20] [--order desc]
  -> writes runs/<name>/plan.json and prints the feasibility / feature table.
  Then launch with:  python scripts/remote_runner.py runs/<name>/sweep.py
  (sweep.py is created from the template if missing; it just runs the plan.)
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from cell_placement import best_shift_filleted   # noqa: E402

DEFAULT_MIN_FEATURE_NM = 30.0      # project-wide default (user, 2026-10-14); override with --min-feature / --no-min-feature

DIAMOND = dict(E=1050e9, nu=0.07, rho=3500.0, label='Diamond')

SWEEP_TEMPLATE = '''"""
sweep.py for {name} -- generated by scripts/sweep_plan.py.
Runs every combo with "run": true in plan.json via scripts/plan_runner.py.
Re-run scripts/sweep_plan.py (same --name) to change the plan; this file stays the same.

Launch:  python scripts/remote_runner.py runs/{name}/sweep.py
"""
from plan_runner import run_plan

run_plan('{name}__plan.json', run_name='{name}')   # remote_runner uploads plan.json as <run>__plan.json
'''


def parse_list(s):
    """'400:1000:100' (inclusive range) or '0.41,0.45,0.48'."""
    if ':' in s:
        lo, hi, step = (float(x) for x in s.split(':'))
        n = int(round((hi - lo) / step)) + 1
        return [round(lo + i * step, 6) for i in range(n)]
    return [float(x) for x in s.split(',')]


def tag_of(a_nm, da, wa):
    return f'a{int(round(a_nm))}_da{int(round(da * 100)):02d}_wa{int(round(wa * 100)):02d}'


def build_plan(a_list, da_list, wa_list, fr_nm=16.0, t_nm=140.0, min_feature_nm=DEFAULT_MIN_FEATURE_NM,
               enforce_min_feature=True, n_mode=10, n_seg=7, f_mech_ref=(10e9, 300e-9),
               order='desc', material=DIAMOND, min_clearance_nm=1.0, mesh_tet=None, mesh_tri=None):
    combos = []
    a_iter = sorted(a_list, reverse=(order == 'desc'))
    for a_nm in a_iter:
        for da in da_list:
            for wa in wa_list:
                a = a_nm * 1e-9
                d, w = da * a, wa * a
                shift, clr, br = best_shift_filleted(a, d, w, fr_nm * 1e-9)
                clr_nm, br_nm, w_nm = clr * 1e9, br * 1e9, w * 1e9
                if clr_nm < min_clearance_nm:
                    status = 'infeasible_geom'
                elif min_feature_nm is not None and min(br_nm, w_nm) < min_feature_nm:
                    status = 'below_min_feature'
                else:
                    status = 'ok'
                run = status == 'ok' or (status == 'below_min_feature' and not enforce_min_feature)
                combos.append(dict(tag=tag_of(a_nm, da, wa), a_nm=a_nm, da=da, wa=wa,
                                   d_nm=round(d * 1e9, 3), w_nm=round(w_nm, 3),
                                   shift_x=float(shift[0]), shift_y=float(shift[1]),
                                   clearance_nm=round(clr_nm, 2), bridge_nm=round(br_nm, 2),
                                   min_feature_nm=round(min(br_nm, w_nm), 2),
                                   status=status, run=bool(run)))
    return dict(
        geometry=dict(t_nm=t_nm, f_r_nm=fr_nm, model='unit_cell_3.mph'),
        material=material,
        solver=dict(N_mode=n_mode, n_seg=n_seg, f_mech_ref_Hz=f_mech_ref[0], f_mech_ref_a_m=f_mech_ref[1],
                    f_mech_rule='f_mech = f_mech_ref_Hz * f_mech_ref_a_m / a'),
        mesh=dict(tet_hmax=mesh_tet, tri_hmax=mesh_tri,
                  note='Mech Mesh mesh1: ftet1/size1 and ftri1/size1 hmax; None = keep model value '
                       '(t/7.5 and t/8)'),
        fab_check=dict(min_feature_nm=min_feature_nm, enforce=bool(enforce_min_feature),
                       features='narrowest slab bridge, arm width w (fillet radius reported separately)'),
        combos=combos)


def print_table(plan):
    fc = plan['fab_check']
    mf = fc['min_feature_nm']
    print(f"min feature check: {'ON' if fc['enforce'] else 'OFF (flag only)'}"
          f"{'' if mf is None else f', threshold {mf:g} nm'};  fillet radius {plan['geometry']['f_r_nm']:g} nm")
    mh = plan.get('mesh', {})
    print(f"Mech mesh: tet hmax={mh.get('tet_hmax') or 'model default (t/7.5)'}, "
          f"tri hmax={mh.get('tri_hmax') or 'model default (t/8)'};  N_mode={plan['solver']['N_mode']}, "
          f"n_seg={plan['solver']['n_seg']}")
    print(f"{'tag':>20} | {'bridge':>7} {'w':>6} {'clear':>6} | {'status':>18} run")
    for c in plan['combos']:
        print(f"{c['tag']:>20} | {c['bridge_nm']:7.1f} {c['w_nm']:6.1f} {c['clearance_nm']:6.1f} | "
              f"{c['status']:>18} {'yes' if c['run'] else 'no'}")
    n = len(plan['combos']); nr = sum(c['run'] for c in plan['combos'])
    by = {}
    for c in plan['combos']:
        by[c['status']] = by.get(c['status'], 0) + 1
    print(f'\n{nr}/{n} combos will run.  ' + ', '.join(f'{k}: {v}' for k, v in sorted(by.items())))


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--name', required=True, help='run folder name under runs/')
    ap.add_argument('--a', required=True, help='lattice constants in nm, e.g. 400:1000:100 or 400,600')
    ap.add_argument('--da', required=True, help='d/a values, e.g. 0.41,0.45,0.48')
    ap.add_argument('--wa', required=True, help='w/a values, e.g. 0.22,0.26,0.30')
    ap.add_argument('--fr', type=float, default=16.0, help='fillet radius f_r in nm (default 16)')
    ap.add_argument('--t', type=float, default=140.0, help='slab thickness in nm (default 140)')
    g = ap.add_mutually_exclusive_group()
    g.add_argument('--min-feature', type=float, default=DEFAULT_MIN_FEATURE_NM,
                   help=f'minimum feature size in nm (default {DEFAULT_MIN_FEATURE_NM:g})')
    g.add_argument('--no-min-feature', action='store_true',
                   help='do not exclude combos below the threshold (they are still flagged)')
    ap.add_argument('--n-mode', type=int, default=10)
    ap.add_argument('--n-seg', type=int, default=7)
    ap.add_argument('--order', choices=['asc', 'desc'], default='desc', help='order of a (default largest first)')
    ap.add_argument('--mesh-tet', default=None, help="Mech Mesh tetra hmax expression, e.g. 't/5' (model default t/7.5)")
    ap.add_argument('--mesh-tri', default=None, help="Mech Mesh periodic-face hmax, e.g. 't/5.33' (model default t/8)")
    ap.add_argument('--dry-run', action='store_true', help='print the table only, write nothing')
    args = ap.parse_args()

    plan = build_plan(parse_list(args.a), parse_list(args.da), parse_list(args.wa),
                      fr_nm=args.fr, t_nm=args.t, min_feature_nm=args.min_feature,
                      enforce_min_feature=not args.no_min_feature, n_mode=args.n_mode,
                      n_seg=args.n_seg, order=args.order, mesh_tet=args.mesh_tet, mesh_tri=args.mesh_tri)
    print_table(plan)
    if args.dry_run:
        sys.exit(0)
    run_dir = Path('runs') / args.name
    (run_dir / 'data').mkdir(parents=True, exist_ok=True)
    (run_dir / 'figures').mkdir(parents=True, exist_ok=True)
    (run_dir / 'plan.json').write_text(json.dumps(plan, indent=1))
    sweep = run_dir / 'sweep.py'
    if not sweep.exists():
        sweep.write_text(SWEEP_TEMPLATE.format(name=args.name))
    print(f'\nWrote {run_dir}/plan.json (sweep script: {sweep})')
